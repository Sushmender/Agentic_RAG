"""
backend/evaluation/gold_dataset.py
Gold dataset loader and rule-based generator for RAG evaluation.

Gold dataset format (data/gold_dataset.json):
[
  {
    "question": "...",
    "expected_document_ids": ["<doc_id>"],
    "expected_chunk_ids": ["<chunk_id>", ...]
  }
]

Strategy:
  - Load from data/gold_dataset.json if the file exists.
  - Otherwise, scan data/ade_outputs/*/chunks.json for indexed documents and
    generate 2-3 questions per document using rule-based templates (no LLM).
  - Save the generated dataset to data/gold_dataset.json.
  - Each entry is scoped to ONE document (expected_document_ids has 1 item).

Rule-based question templates (no LLM — deterministic):
  - text  chunk: "What information is described in the section about {topic}?"
  - table chunk: "What are the details shown in the {table_title} table?"
  - figure chunk: "What does the figure on page {page_num} show?"

Document-level questions are generated by combining the 3 chunk-type templates
limited to 2-3 questions per document to keep the gold set focused.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

from app.core.config import get_settings
from app.core.logging import get_logger

logger = get_logger(__name__)
settings = get_settings()

GOLD_DATASET_PATH = Path("./data/gold_dataset.json")


# ── Public API ─────────────────────────────────────────────────────────────────

def load_or_generate() -> List[Dict[str, Any]]:
    """
    Load the gold dataset from disk, or generate it if it doesn't exist.

    Returns:
        List of gold entries, each with:
            question, expected_document_ids, expected_chunk_ids
    """
    if GOLD_DATASET_PATH.exists():
        data = json.loads(GOLD_DATASET_PATH.read_text(encoding="utf-8"))
        logger.info("Gold dataset loaded from disk", path=str(GOLD_DATASET_PATH), entries=len(data))
        return data

    logger.info("No gold dataset found — generating from indexed documents")
    dataset = _generate()
    _save(dataset)
    return dataset


def load() -> Optional[List[Dict[str, Any]]]:
    """Load the gold dataset only if it exists. Returns None otherwise."""
    if not GOLD_DATASET_PATH.exists():
        return None
    return json.loads(GOLD_DATASET_PATH.read_text(encoding="utf-8"))


def save(dataset: List[Dict[str, Any]]) -> None:
    """Persist a gold dataset to data/gold_dataset.json."""
    _save(dataset)


# ── Generation ─────────────────────────────────────────────────────────────────

def _generate() -> List[Dict[str, Any]]:
    """
    Scan data/ade_outputs/*/chunks.json and produce 2-3 gold questions
    per indexed document using rule-based templates.
    """
    ade_dir = Path(settings.ADE_OUTPUT_DIR)
    if not ade_dir.exists():
        logger.warning("ADE output directory not found", path=str(ade_dir))
        return []

    dataset: List[Dict[str, Any]] = []

    doc_dirs = [d for d in ade_dir.iterdir() if d.is_dir()]
    if not doc_dirs:
        logger.warning("No indexed documents found in ADE output directory")
        return []

    for doc_dir in doc_dirs:
        chunks_path = doc_dir / "chunks.json"
        if not chunks_path.exists():
            continue

        document_id = doc_dir.name
        chunks = json.loads(chunks_path.read_text(encoding="utf-8"))

        if not chunks:
            continue

        entries = _generate_for_document(document_id, chunks)
        dataset.extend(entries)
        logger.info(
            "Generated gold questions for document",
            document_id=document_id[:16] + "...",
            questions=len(entries),
        )

    logger.info("Gold dataset generation complete", total_entries=len(dataset))
    return dataset


def _generate_for_document(
    document_id: str,
    chunks: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """
    Generate 2-3 gold questions for a single document.

    Strategy: pick one text chunk, one table chunk, one figure chunk
    (whichever types are available) — generate one question per type.
    Capped at 3 questions per document.
    """
    entries: List[Dict[str, Any]] = []
    used_types: set[str] = set()

    for chunk in chunks:
        chunk_type = chunk.get("chunk_type", "text")
        if chunk_type in used_types:
            continue  # one question per chunk type per document

        question = _question_from_chunk(chunk)
        if not question:
            continue

        entry: Dict[str, Any] = {
            "question": question,
            "expected_document_ids": [document_id],
            "expected_chunk_ids": [chunk["chunk_id"]],
        }
        entries.append(entry)
        used_types.add(chunk_type)

        if len(entries) >= 3:
            break

    return entries


def _question_from_chunk(chunk: Dict[str, Any]) -> Optional[str]:
    """
    Build a natural-language question from a single chunk using rule-based templates.
    Returns None if the chunk has no usable content.
    """
    chunk_type = chunk.get("chunk_type", "text")
    text = chunk.get("text", "").strip()
    page = chunk.get("page", 0)

    if not text:
        return None

    if chunk_type == "text":
        # Extract first non-empty line as topic
        topic = _extract_topic(text)
        return f"What information is described in the section about {topic}?"

    elif chunk_type == "table":
        # Extract table title from text before <table> tag
        title = _extract_table_title(text)
        return f"What are the details shown in the {title} table?"

    elif chunk_type == "figure":
        return f"What does the figure on page {page + 1} show?"

    else:
        # Fallback for unknown types
        topic = _extract_topic(text)
        return f"What does the content about {topic} describe?"


# ── Helpers ────────────────────────────────────────────────────────────────────

def _extract_topic(text: str) -> str:
    """
    Extract a short topic phrase from text content.
    Strips markdown headers, HTML tags, IDs, and takes the first meaningful line.
    """
    # Remove HTML tags (anchor tags from ADE output)
    clean = re.sub(r"<[^>]+>", "", text)
    # Remove markdown heading markers
    clean = re.sub(r"^#+\s*", "", clean, flags=re.MULTILINE)
    # Remove leading/trailing whitespace per line, take first non-empty line
    lines = [ln.strip() for ln in clean.splitlines() if ln.strip()]
    topic = lines[0] if lines else "this topic"
    # Truncate long topics
    return topic[:60] if len(topic) > 60 else topic


def _extract_table_title(text: str) -> str:
    """
    Extract the table title from ADE table chunk text.
    Table text typically has a heading before the <table> tag.
    """
    # Remove HTML tags
    clean = re.sub(r"<[^>]+>", "", text)
    # Remove markdown heading markers
    clean = re.sub(r"^#+\s*", "", clean, flags=re.MULTILINE)
    # Take the first non-empty line as the title
    lines = [ln.strip() for ln in clean.splitlines() if ln.strip()]
    title = lines[0] if lines else "this"
    # Truncate
    return title[:60] if len(title) > 60 else title


def _save(dataset: List[Dict[str, Any]]) -> None:
    """Persist a gold dataset to data/gold_dataset.json."""
    GOLD_DATASET_PATH.parent.mkdir(parents=True, exist_ok=True)
    GOLD_DATASET_PATH.write_text(
        json.dumps(dataset, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    logger.info("Gold dataset saved", path=str(GOLD_DATASET_PATH), entries=len(dataset))
